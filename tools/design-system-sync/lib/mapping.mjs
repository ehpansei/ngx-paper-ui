/*
 * The contract: which design-system file comes from which repo file, and who owns it.
 *   owner 'repo'  → the repo is canonical; a DS-side edit is flagged as `remote-edit`, never silently overwritten
 *   owner 'both'  → either side may edit; 3-way merged against the last synced base
 * Files the DS alone owns (Cover, the page-generated tokens.css / api/ / manifest.json) are never listed.
 */
import { readdirSync } from 'node:fs';
import { join, relative } from 'node:path';
import { authorPart, iconToDs, joinCss } from './convert.mjs';
import { cardOf, loadDocs, readmePath, renderDts, renderPreview } from './docs.mjs';
import { read, walk } from './fsutil.mjs';
import { BRAND_BOOK, BUILD, ICONS_DIR, LIB, LIB_SRC, PAGES, REMOTE, SAMPLE_DATA, TOKENS_JSON, r } from './paths.mjs';

/** Prefixes on the DS side that the repo owns entirely: a DS file there that the repo doesn't produce is `remove?`. */
export const REPO_PREFIXES = ['components/src/'];

/**
 * Renders the repo as DS files. Returns Map<dsPath, { text, owner, repo }> where `repo` names the repo
 * file(s) it comes from (for pulls and the report). `bundleJs` is added by the caller after the build.
 */
export function stageEntries() {
  const entries = new Map();
  const add = (ds, text, owner, repo, source) => entries.set(ds, { text, owner, repo, source });
  const rel = (p) => relative(r(), p);

  // Tokens and brand book (two-way).
  const tokensText = read(TOKENS_JSON);
  add('tokens.json', tokensText, 'both', rel(TOKENS_JSON));
  const brand = read(BRAND_BOOK);
  add('README.md', brand == null ? null : authorPart(brand), 'both', rel(BRAND_BOOK)); // null until seeded by a pull

  // Icons (two-way; DS form uses a fixed ink).
  for (const f of readdirSync(ICONS_DIR).filter((x) => x.endsWith('.svg')).sort())
    add(`assets/Icons/${f}`, iconToDs(read(join(ICONS_DIR, f))), 'both', rel(join(ICONS_DIR, f)));

  // Component cards: guideline README (two-way), preview.html (repo), plus index.d.ts.
  const tokens = JSON.parse(tokensText);
  const docs = loadDocs();
  for (const doc of docs) {
    const readme = r(readmePath(doc));
    const text = read(readme);
    add(`components/${doc.name}/README.md`, text, 'both', rel(readme), doc.libFile); // null until seeded by a pull
    const card = cardOf(read(join(REMOTE, 'project/components', doc.name, 'preview.html')));
    add(`components/${doc.name}/preview.html`, renderPreview(doc, tokens, card), 'repo', doc.file);
  }
  const iconNames = readdirSync(ICONS_DIR).filter((x) => x.endsWith('.svg')).map((x) => x.slice(0, -4)).sort((a, b) => a.localeCompare(b, 'en'));
  add('components/index.d.ts', renderDts(docs, iconNames), 'repo', 'apps/ui-demo-app/src/app/pages/*/*.docs.ts');

  // Component CSS (repo).
  add('components/bundle.css', joinCss(), 'repo', 'libs/ui/src/styles/paper-ui/*.css');

  // Sources (repo): the library, then the docs showcases + the mount entry.
  for (const f of walk(LIB_SRC).filter((x) => x.endsWith('.ts') && !x.endsWith('.spec.ts') && x !== 'test-setup.ts'))
    add(`components/src/angular/${f}`, read(join(LIB_SRC, f)), 'repo', rel(join(LIB_SRC, f)));
  for (const doc of docs) {
    const f = join(PAGES, `${doc.kebab}-docs-page`, `${doc.kebab}-showcase.ts`);
    add(`components/src/docs/showcases/${doc.kebab}-showcase.ts`, read(f), 'repo', rel(f));
  }
  add('components/src/docs/sample-data.ts', read(SAMPLE_DATA), 'repo', rel(SAMPLE_DATA));
  add('components/src/docs/mount.ts', mountSource(docs), 'repo', 'tools/design-system-sync (generated)');

  return { entries, docs };
}

/** The bundle entry: every showcase by DS card name, mounted zoneless like the DS's own runtime. */
export function mountSource(docs, importBase = '../showcases', spriteImport = '../../../assets/icons.svg?raw') {
  const imports = docs.map((d) => `import { ${d.name}Showcase } from '${importBase}/${d.kebab}-showcase';`).join('\n');
  return `/*
 * Documentation runtime: window.PaperUI.mount('Button', element) bootstraps that component's showcase
 * with real Angular — zoneless, standalone, OnPush. GENERATED by tools/design-system-sync.
 */
import { ApplicationRef, enableProdMode, provideZonelessChangeDetection, Type } from '@angular/core';
import { createApplication } from '@angular/platform-browser';
import { provideIconSprite } from 'ngx-paper-ui';
import sprite from '${spriteImport}';
${imports}

enableProdMode();

const SHOWCASES: Record<string, Type<unknown>> = {
${docs.map((d) => `  ${d.name}: ${d.name}Showcase,`).join('\n')}
};

let app: Promise<ApplicationRef> | undefined;

export async function mount(name: string, element: HTMLElement) {
  const component = SHOWCASES[name];
  if (!component) throw new Error(\`No showcase named \${name}\`);
  // Self-contained: the icon sprite is inlined into the page once and <lib-icon> points at it (#lock),
  // so the design system needs no separate icons.svg asset.
  if (!document.getElementById('lib-icon-sprite')) {
    const holder = document.createElement('div');
    holder.id = 'lib-icon-sprite';
    holder.setAttribute('aria-hidden', 'true');
    holder.style.cssText = 'position:absolute;width:0;height:0;overflow:hidden';
    holder.innerHTML = sprite;
    document.body.prepend(holder);
  }
  app ??= createApplication({ providers: [provideZonelessChangeDetection(), provideIconSprite('')] });
  return (await app).bootstrap(component, element);
}

export const components = Object.keys(SHOWCASES);
`;
}

/** The build entry in dist/ds-sync/build, importing the showcases straight from the docs app. */
export function buildEntry(docs) {
  const base = relative(BUILD, PAGES).split('\\').join('/');
  const sprite = relative(BUILD, ICONS_DIR).split('\\').join('/').replace(/icons$/, 'icons.svg?raw');
  return mountSource(docs, 'X', sprite).replace(/'X\/([\w-]+)-showcase'/g, (_, k) => `'${base}/${k}-docs-page/${k}-showcase'`);
}

export const bundleHeader = (docs, namespace) =>
  `/* @ds-bundle: ${JSON.stringify({ format: 4, namespace, components: docs.map((d) => ({ name: d.name })) })} */\n`;

export const LIB_ROOT = LIB;
