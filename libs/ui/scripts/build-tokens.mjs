// Generates the CSS side of the Paper UI tokens from src/styles/tokens/tokens.json (the source of truth,
// synced with the design system). Run with `nx run ui:tokens` (also runs before `nx build ui`). Outputs:
//   src/styles/tokens/tokens.css           — custom properties, light on :root, dark on [data-theme="dark"]
//   apps/ui-demo-app/src/app/docs/tokens.json — the docs site's copy (token tables)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokensDir = join(root, 'src/styles/tokens');
const source = join(tokensDir, 'tokens.json');
const demoCopy = join(root, '../../apps/ui-demo-app/src/app/docs/tokens.json');

const raw = readFileSync(source, 'utf8');
const t = JSON.parse(raw);

// Derived in ../paper-ui/base.css from --primary with color-mix(); never set here (derived-tokens.json).
const DERIVED = new Set(JSON.parse(readFileSync(join(tokensDir, 'derived-tokens.json'), 'utf8')));
const FAMILIES = ['color', 'spacing', 'radius', 'shadow', 'typeScale', 'size', 'opacity', 'breakpoint'];
const val = (v) => String(v).replace(/^\{([\w.-]+)\}$/, 'var(--$1)');

const light = [];
const dark = [];
for (const fam of FAMILIES) {
  if (!t[fam]?.tokens) continue;
  light.push(`\n  /* ${fam} */`);
  let darkHeader = false;
  for (const tok of t[fam].tokens) {
    if (DERIVED.has(tok.name)) continue;
    const v = tok.value;
    if (v && typeof v === 'object') {
      light.push(`  --${tok.name}: ${val(v.light)};`);
      if (v.dark !== undefined && v.dark !== v.light) {
        if (!darkHeader) {
          dark.push(`\n  /* ${fam} */`);
          darkHeader = true;
        }
        dark.push(`  --${tok.name}: ${val(v.dark)};`);
      }
    } else {
      light.push(`  --${tok.name}: ${val(v)};`);
    }
  }
}
light.push(`\n  /* type */`, `  --font-sans: ${t.type.families.sans};`);
const styles = t.type.groups.flatMap((g) => g.styles);

writeFileSync(
  join(tokensDir, 'tokens.css'),
  `/*
 * Paper UI design tokens — GENERATED by libs/ui/scripts/build-tokens.mjs from tokens.json. Do not edit:
 * change tokens.json (or the design system, then sync) and run \`nx run ui:tokens\`.
 * Light values on :root, dark overrides on [data-theme="dark"].
 * primary / on-primary are the only configurable colours. primary-hover, primary-text, primary-soft,
 * focus-ring, nav-item-active-bg, shadow-focus and the button/nav/card primary aliases are derived
 * from --primary in ../paper-ui/base.css and are intentionally not set here.
 */
:root, [data-theme="light"] {${light.join('\n')}
}

[data-theme="dark"] {${dark.join('\n')}
}

/* Type styles */
${styles
  .map(
    (s) =>
      `.type-${s.name} { font-size: ${s.fontSize}; line-height: ${s.lineHeight}; font-weight: ${s.fontWeight};` +
      `${s.letterSpacing ? ` letter-spacing: ${s.letterSpacing};` : ''}${s.name === 'overline' ? ' text-transform: uppercase;' : ''} }`,
  )
  .join('\n')}
`,
);

writeFileSync(demoCopy, raw);
writeFileSync(join(dirname(demoCopy), 'derived-tokens.json'), readFileSync(join(tokensDir, 'derived-tokens.json'), 'utf8'));
console.log('tokens: tokens.css, apps/ui-demo-app/src/app/docs/tokens.json');
