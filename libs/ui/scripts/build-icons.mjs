// Builds the icon sprite, the IconName type and the inline sprite data from libs/ui/src/assets/icons/*.svg.
// Run with `nx run ui:icons` (also runs before `nx build ui`). Never edit the outputs by hand.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = join(root, 'src/assets/icons');
const spriteFile = join(root, 'src/assets/icons.svg');
const namesFile = join(root, 'src/components/icon/icon-names.ts');
const dataFile = join(root, 'src/components/icon/icon-sprite-data.ts');

const files = readdirSync(iconsDir)
  .filter((f) => f.endsWith('.svg'))
  .sort((a, b) => a.slice(0, -4).localeCompare(b.slice(0, -4), 'en'));
if (!files.length) throw new Error(`No icons found in ${iconsDir}`);

const symbols = files.map((file) => {
  const name = file.slice(0, -'.svg'.length);
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) throw new Error(`${file}: icon names must be kebab-case`);
  const svg = readFileSync(join(iconsDir, file), 'utf8');
  if (!/<svg\b[^>]*\bviewBox="0 0 24 24"/.test(svg)) throw new Error(`${file}: expected viewBox="0 0 24 24" (24px grid)`);
  const inner = svg.replace(/^[\s\S]*?<svg\b[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
  if (!inner) throw new Error(`${file}: no shapes`);
  if (/\b(stroke|fill)="(?!none|currentColor)/.test(inner)) {
    throw new Error(`${file}: shapes must not set their own colour; they inherit currentColor from <lib-icon>`);
  }
  // Stroke attributes live on the <svg> that renders the icon (width, stroke-width), so symbols carry only shapes.
  return { name, body: inner.replace(/\s*\n\s*/g, '') };
});

const sprite =
  `<svg xmlns="http://www.w3.org/2000/svg">\n` +
  symbols.map((s) => `  <symbol id="${s.name}" viewBox="0 0 24 24">${s.body}</symbol>\n`).join('') +
  `</svg>\n`;
writeFileSync(spriteFile, sprite);

// The same sprite as a string, for provideInlineIconSprite() (no asset to serve).
writeFileSync(
  dataFile,
  `// GENERATED by libs/ui/scripts/build-icons.mjs from src/assets/icons/*.svg — do not edit.\n` +
    `// The icon sprite as markup, inlined into the page by provideInlineIconSprite().\n\n` +
    `export const ICON_SPRITE_SVG = ${JSON.stringify(sprite.replace(/\n\s*/g, ''))};\n`,
);

writeFileSync(
  namesFile,
  `// GENERATED by libs/ui/scripts/build-icons.mjs from src/assets/icons/*.svg — do not edit.\n` +
    `// To add an icon, add <name>.svg there and run \`nx run ui:icons\`.\n\n` +
    `export const ICON_NAMES = [\n${symbols.map((s) => `  '${s.name}',`).join('\n')}\n] as const;\n\n` +
    `export type IconName = (typeof ICON_NAMES)[number];\n`,
);

console.log(`icons: ${symbols.length} symbols → ${[spriteFile, namesFile, dataFile].map((f) => f.slice(root.length + 1)).join(', ')}`);
