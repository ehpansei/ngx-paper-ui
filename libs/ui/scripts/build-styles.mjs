// Generates the published stylesheets from the library's style sources. Run with `nx run ui:styles` (also runs
// before `nx build ui`, after ui:tokens). Output, copied to the package root by ng-package.json:
//   src/styles/package/paper-ui.css  — plain CSS for any app: the Inter import, tokens.css, then every
//                                      paper-ui/*.css in the order index.css imports them
// src/styles/index.css (the docs app's in-repo entry) is a source, not an output.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fontImport, joinCss, STYLES_DIR } from './css-parts.mjs';

const outDir = join(STYLES_DIR, 'package');
const tokens = readFileSync(join(STYLES_DIR, 'tokens/tokens.css'), 'utf8').trimEnd();
const components = joinCss(undefined, { font: false }).trimEnd();

const header = (what) => `/*
 * Paper UI — ${what}
 * GENERATED by libs/ui/scripts/build-styles.mjs from src/styles/ (tokens/ and paper-ui/). Do not edit.
 */`;

mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, 'paper-ui.css'),
  [
    fontImport()?.trim() ?? '',
    header('the complete stylesheet as plain CSS. Components use only ui-* classes.'),
    tokens,
    components,
  ]
    .filter(Boolean)
    .join('\n\n') + '\n',
);
console.log('styles: src/styles/package/paper-ui.css');
